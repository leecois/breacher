//! Corpus evaluation, template learning and layout calibration.
use crate::corpus::{self, Item};
use crate::imgio;
use breach_core::glyph::{self, Feat, TemplateSet, Templates, NCODES};
use breach_core::reader::{self, Contrast, ReadOptions, Stage};
use std::collections::BTreeMap;
use std::path::Path;

/// Labelled glyph features of one image, split by where they came from.
pub struct Samples {
    pub style: String,
    pub matrix: Vec<(u8, Feat)>,
    pub seq: Vec<(u8, Feat)>,
}

/// Locate the screen in the unperturbed image and pair its glyph features with the labels.
pub fn samples(item: &Item, opt: &ReadOptions) -> Result<Samples, String> {
    let img = imgio::load(&item.path)?;
    samples_from(item, &img, &item.label.style, opt)
}

/// Same for an already-loaded (possibly degraded) image, filed under `style`.
pub fn samples_from(
    item: &Item,
    img: &image::RgbImage,
    style: &str,
    opt: &ReadOptions,
) -> Result<Samples, String> {
    let loc = reader::locate(&imgio::frame(img), opt).map_err(|e| format!("{}: {e}", item.name))?;
    let n = loc.geometry.n;
    if n != item.label.matrix.len()
        || loc.seq_feats.len() != item.label.sequences.len()
        || loc.seq_feats.iter().zip(&item.label.sequences).any(|(a, b)| a.len() != b.len())
    {
        return Err(format!(
            "{}: located shape does not match labels (n {n}, {} sequences)",
            item.name,
            loc.seq_feats.len()
        ));
    }
    let mut matrix = Vec::new();
    for (i, f) in loc.matrix_feats.into_iter().enumerate() {
        if let Some(f) = f {
            matrix.push((item.label.matrix[i / n][i % n], f));
        }
    }
    let mut seq = Vec::new();
    for (r, row) in loc.seq_feats.into_iter().enumerate() {
        for (k, f) in row.into_iter().enumerate() {
            if let Some(f) = f {
                seq.push((item.label.sequences[r][k], f));
            }
        }
    }
    Ok(Samples { style: style.to_string(), matrix, seq })
}

/// One template set per (style, matrix|seq), averaged over the given images.
pub fn build_sets(all: &[(String, Samples)], exclude: Option<&str>) -> Vec<TemplateSet> {
    let mut groups: BTreeMap<String, Vec<(u8, Feat)>> = BTreeMap::new();
    for (name, s) in all {
        if Some(name.as_str()) == exclude {
            continue;
        }
        groups.entry(format!("{}-matrix", s.style)).or_default().extend(s.matrix.iter().cloned());
        groups.entry(format!("{}-seq", s.style)).or_default().extend(s.seq.iter().cloned());
    }
    groups.iter().map(|(name, v)| glyph::learn_set(name, v)).collect()
}

/// Labelled samples of every positive image; with `soft`, also from blurred and compressed copies, filed under "<style>-soft".
pub fn collect(items: &[Item], opt: &ReadOptions, soft: bool) -> Vec<(String, Samples)> {
    let mut out = Vec::new();
    for it in items.iter().filter(|i| !i.label.negative) {
        match samples(it, opt) {
            Ok(s) => out.push((it.name.clone(), s)),
            Err(e) => eprintln!("  (no samples) {e}"),
        }
        if soft {
            if let Ok(img) = imgio::load(&it.path) {
                let style = format!("{}-soft", it.label.style);
                for degraded in [
                    imgio::blur(&img, 1.0),
                    imgio::jpeg(
                        &imgio::blur(&imgio::rescale(&img, (img.height() * 2 / 3).max(540)), 0.7),
                        45,
                    ),
                ] {
                    if let Ok(s) = samples_from(it, &degraded, &style, opt) {
                        out.push((it.name.clone(), s));
                    }
                }
            }
        }
    }
    out
}

pub fn write_templates(sets: &[TemplateSet], path: &Path) -> Result<(), String> {
    let mut s = String::from(
        "//! Generated by `breach learn-templates`: quantised (i8) 32x24 template bitmaps; an all-zero entry means the style has no sample of that token.\n#[rustfmt::skip]\npub const SETS: &[(&str, [[i8; 768]; 6])] = &[\n",
    );
    for set in sets {
        s.push_str(&format!("    (\"{}\", [\n", set.name));
        for k in 0..NCODES {
            let q: Vec<i8> = match set.codes.get(k).and_then(|c| c.as_ref()) {
                Some(f) => {
                    let m = f.iter().fold(0f32, |a, v| a.max(v.abs())).max(1e-9);
                    f.iter().map(|v| (v / m * 127.0).round() as i8).collect()
                }
                None => vec![0; glyph::GN],
            };
            s.push_str("        [");
            s.push_str(&q.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(","));
            s.push_str("],\n");
        }
        s.push_str("    ]),\n");
    }
    s.push_str("];\n");
    std::fs::write(path, s).map_err(|e| e.to_string())
}

pub struct EvalArgs {
    pub full: bool,
    pub loo: bool,
    pub contrast: Contrast,
    pub verbose: bool,
    pub only: Option<String>,
    pub only_pert: Option<String>,
    pub soft: bool,
    /// Add this to the layout's predicted sequence-column offset (pitch units): simulates a moved panel.
    pub seq_shift: f32,
    /// Add this to the layout's predicted buffer row (pitch units).
    pub buffer_shift: f32,
}

#[derive(Default, Clone)]
struct Agg {
    pos: u32,
    ok: u32,
    matrix_ok: u32,
    seq_ok: u32,
    buf_ok: u32,
    cells: u32,
    cells_wrong: u32,
    silent_wrong: u32,
    rejected: u32,
    neg: u32,
    neg_rejected: u32,
    by_stage: BTreeMap<String, u32>,
}

pub fn run(dir: &Path, args: &EvalArgs) -> Result<(), String> {
    let items = corpus::load(dir)?;
    let mut opt = ReadOptions { contrast: args.contrast, ..ReadOptions::default() };
    let all = if args.loo { collect(&items, &opt, args.soft) } else { Vec::new() };
    // templates are always learned with the true layout; only the frames under test see the shift
    opt.layout.seq_col_offset += args.seq_shift;
    opt.layout.buffer_row += args.buffer_shift;
    let builtin = Templates::builtin();
    if !args.loo && builtin.is_empty() {
        return Err("no built-in templates yet: run `breach learn-templates` or use --loo".into());
    }
    let suite = imgio::suite(args.full);
    let mut agg: BTreeMap<usize, Agg> = BTreeMap::new();
    let mut times: Vec<(f64, reader::Timings)> = Vec::new();
    let mut lines: Vec<String> = Vec::new();
    for it in &items {
        if let Some(o) = &args.only {
            if &it.name != o {
                continue;
            }
        }
        let img0 = imgio::load(&it.path)?;
        let templates = if args.loo {
            Templates { sets: build_sets(&all, Some(&it.name)) }
        } else {
            builtin.clone()
        };
        for (pi, (pname, f)) in suite.iter().enumerate() {
            if args.only_pert.as_deref().is_some_and(|o| o != *pname) {
                continue;
            }
            let img = f(&img0);
            let res = reader::read(&imgio::frame(&img), &templates, &opt);
            let a = agg.entry(pi).or_default();
            if it.label.negative {
                a.neg += 1;
                match &res {
                    Err(e) => {
                        a.neg_rejected += 1;
                        if args.verbose {
                            lines
                                .push(format!("{:<7} {:<16} NEG    rejected  {e}", it.name, pname));
                        }
                    }
                    Ok(_) => {
                        lines.push(format!("{:<7} {:<16} NEG    FALSE-ACCEPT", it.name, pname))
                    }
                }
                continue;
            }
            a.pos += 1;
            match res {
                Err(e) => {
                    a.rejected += 1;
                    *a.by_stage.entry(format!("{:?}", e.stage)).or_default() += 1;
                    lines.push(format!("{:<7} {:<16} reject {e}", it.name, pname));
                }
                Ok(r) => {
                    let gm: Vec<u8> = it.label.matrix.iter().flatten().copied().collect();
                    let m_ok = r.matrix == gm;
                    let s_ok = r.sequences == it.label.sequences;
                    let b_ok = r.buffer == it.label.buffer;
                    if r.matrix.len() == gm.len() {
                        a.cells += gm.len() as u32;
                        a.cells_wrong +=
                            r.matrix.iter().zip(&gm).filter(|(x, y)| x != y).count() as u32;
                    }
                    a.matrix_ok += m_ok as u32;
                    a.seq_ok += s_ok as u32;
                    a.buf_ok += b_ok as u32;
                    let ok = m_ok && s_ok && b_ok;
                    a.ok += ok as u32;
                    a.silent_wrong += !ok as u32;
                    times.push(((img.width() * img.height()) as f64 / 1e6, r.timings.clone()));
                    let q = &r.quality;
                    let detail = format!(
                        "n={} px={:.1} py={:.1} d={} x{:.2} cons={:.2} evid={:.2} marg={:.2} sep={:.2} frags={}/{} buf={} (top {:?} side {:?} slots {:?}){} {:.1}ms",
                        r.n, r.geometry.px, r.geometry.py, q.decimation, q.scale_mult, q.min_consistency, q.min_evidence, q.min_margin, q.min_separation, q.matrix_fragments, q.matrix_tokens,
                        r.buffer, q.buffer_from_panel_top, q.buffer_from_panel_side, q.buffer_from_slots, if q.layout_fallback { " FALLBACK" } else { "" },
                        r.timings.total_us as f64 / 1000.0
                    );
                    if !ok {
                        lines.push(format!(
                            "{:<7} {:<16} WRONG  matrix={} seq={} buf={} | {detail}",
                            it.name,
                            pname,
                            if m_ok { "ok" } else { "BAD" },
                            if s_ok { "ok".into() } else { format!("{:?}", r.sequences) },
                            if b_ok {
                                "ok".into()
                            } else {
                                format!("{} (want {})", r.buffer, it.label.buffer)
                            }
                        ));
                    } else if args.verbose || !args.full {
                        lines.push(format!("{:<7} {:<16} ok     {detail}", it.name, pname));
                    }
                }
            }
        }
    }
    for l in &lines {
        println!("{l}");
    }
    println!();
    println!(
        "{:<16} {:>9} {:>7} {:>6} {:>7} {:>10} {:>8} {:>7} {:>8}  rejected at",
        "perturbation",
        "full-read",
        "matrix",
        "seqs",
        "buffer",
        "cell-err",
        "silent",
        "reject",
        "neg-rej"
    );
    let mut tot = Agg::default();
    for (pi, (pname, _)) in suite.iter().enumerate() {
        let Some(a) = agg.get(&pi) else { continue };
        println!(
            "{:<16} {:>5}/{:<3} {:>4}/{:<2} {:>3}/{:<2} {:>4}/{:<2} {:>5}/{:<4} {:>8} {:>7} {:>5}/{:<2}  {}",
            pname, a.ok, a.pos, a.matrix_ok, a.pos, a.seq_ok, a.pos, a.buf_ok, a.pos, a.cells_wrong, a.cells, a.silent_wrong, a.rejected, a.neg_rejected, a.neg,
            a.by_stage.iter().map(|(k, v)| format!("{k}:{v}")).collect::<Vec<_>>().join(" ")
        );
        tot.pos += a.pos;
        tot.ok += a.ok;
        tot.matrix_ok += a.matrix_ok;
        tot.seq_ok += a.seq_ok;
        tot.buf_ok += a.buf_ok;
        tot.cells += a.cells;
        tot.cells_wrong += a.cells_wrong;
        tot.silent_wrong += a.silent_wrong;
        tot.rejected += a.rejected;
        tot.neg += a.neg;
        tot.neg_rejected += a.neg_rejected;
        for (k, v) in &a.by_stage {
            *tot.by_stage.entry(k.clone()).or_default() += v;
        }
    }
    println!(
        "{:<16} {:>5}/{:<3} {:>4}/{:<2} {:>3}/{:<2} {:>4}/{:<2} {:>5}/{:<4} {:>8} {:>7} {:>5}/{:<2}  {}",
        "TOTAL", tot.ok, tot.pos, tot.matrix_ok, tot.pos, tot.seq_ok, tot.pos, tot.buf_ok, tot.pos, tot.cells_wrong, tot.cells, tot.silent_wrong, tot.rejected, tot.neg_rejected, tot.neg,
        tot.by_stage.iter().map(|(k, v)| format!("{k}:{v}")).collect::<Vec<_>>().join(" ")
    );
    if !times.is_empty() {
        let stat = |f: &dyn Fn(&reader::Timings) -> u32| {
            let mut v: Vec<f64> = times.iter().map(|t| f(&t.1) as f64 / 1000.0).collect();
            v.sort_by(|a, b| a.partial_cmp(b).unwrap());
            (v[v.len() / 2], v[((v.len() - 1) as f64 * 0.95) as usize], v[v.len() - 1])
        };
        for (name, f) in [
            ("segment", &(|t: &reader::Timings| t.segment_us) as &dyn Fn(&reader::Timings) -> u32),
            ("lattice", &|t: &reader::Timings| t.lattice_us),
            ("sequences", &|t: &reader::Timings| t.sequences_us),
            ("buffer", &|t: &reader::Timings| t.buffer_us),
            ("classify", &|t: &reader::Timings| t.classify_us),
            ("total", &|t: &reader::Timings| t.total_us),
        ] {
            let (med, p95, max) = stat(f);
            println!("time {name:<9} median {med:>7.2} ms   p95 {p95:>7.2} ms   max {max:>7.2} ms");
        }
    }
    let _ = Stage::Frame;
    Ok(())
}

/// Print measured layout constants (pitch units) for each labelled image.
pub fn calibrate(dir: &Path) -> Result<(), String> {
    let items = corpus::load(dir)?;
    let opt = ReadOptions::default();
    println!(
        "{:<7} {:>2} {:>6} {:>6} | {:>14} {:>12} {:>24} | {:>9} | buffer(top/side/slots) fallback",
        "image", "n", "px", "py", "seq col offset", "seq row0", "row pitch / py", "buffer y"
    );
    for it in items.iter().filter(|i| !i.label.negative) {
        let img = imgio::load(&it.path)?;
        match reader::locate(&imgio::frame(&img), &opt) {
            Err(e) => println!("{:<7} {e}", it.name),
            Ok(l) => {
                let g = &l.geometry;
                let n = g.n as f32;
                let xc = g.x0 + (n - 1.0) / 2.0 * g.px;
                let a = (g.seq_x0 - xc) / g.px - n / 2.0;
                let b = (g.seq_rows[0] - g.y0) / g.py;
                let pit: Vec<String> =
                    g.seq_rows.windows(2).map(|w| format!("{:.3}", (w[1] - w[0]) / g.py)).collect();
                println!(
                    "{:<7} {:>2} {:>6.2} {:>6.2} | {:>14.3} {:>12.3} {:>24} | {:>9.3} | {:?}/{:?}/{:?} {}",
                    it.name, g.n, g.px, g.py, a, b, pit.join(" "), (g.buffer_y - g.y0) / g.py, l.quality.buffer_from_panel_top, l.quality.buffer_from_panel_side, l.quality.buffer_from_slots, l.quality.layout_fallback
                );
            }
        }
    }
    Ok(())
}

/// Similarity statistics of labelled glyphs: how far apart tokens are at the matrix size and at the sequence size.
pub fn separation(dir: &Path) -> Result<(), String> {
    let items = corpus::load(dir)?;
    let opt = ReadOptions::default();
    let perts: Vec<imgio::Perturb> = imgio::suite(true)
        .into_iter()
        .filter(|(n, _)| {
            ["native", "res_720p", "gamma_1.8", "hdr_clip_x4", "blur_1.2", "jpeg_q30", "noise_s8"]
                .contains(n)
        })
        .collect();
    println!("{:<12} | matrix: same min / other max (worst pair) | sequences: same min / other max (worst pair) | matrix-vs-seq: same min / other max", "perturbation");
    for (pname, f) in &perts {
        let (mut ms, mut mo, mut ss, mut so, mut cs, mut co) =
            (1f32, -1f32, 1f32, -1f32, 1f32, -1f32);
        let (mut mpair, mut spair) = ((0u8, 0u8), (0u8, 0u8));
        for it in items.iter().filter(|i| !i.label.negative) {
            let img = f(&imgio::load(&it.path)?);
            let Ok(loc) = reader::locate(&imgio::frame(&img), &opt) else { continue };
            let n = loc.geometry.n;
            if n != it.label.matrix.len()
                || loc.seq_feats.len() != it.label.sequences.len()
                || loc.seq_feats.iter().zip(&it.label.sequences).any(|(a, b)| a.len() != b.len())
            {
                continue;
            }
            let m: Vec<(u8, Feat)> = loc
                .matrix_feats
                .into_iter()
                .enumerate()
                .filter_map(|(i, f)| f.map(|f| (it.label.matrix[i / n][i % n], f)))
                .collect();
            let mut q: Vec<(u8, Feat)> = Vec::new();
            for (r, row) in loc.seq_feats.into_iter().enumerate() {
                for (k, f) in row.into_iter().enumerate() {
                    if let Some(f) = f {
                        q.push((it.label.sequences[r][k], f));
                    }
                }
            }
            let scan = |a: &[(u8, Feat)],
                        b: &[(u8, Feat)],
                        same: &mut f32,
                        other: &mut f32,
                        pair: &mut (u8, u8),
                        sym: bool| {
                for (i, x) in a.iter().enumerate() {
                    for (j, y) in b.iter().enumerate() {
                        if sym && j <= i {
                            continue;
                        }
                        let d = glyph::dot(&x.1, &y.1);
                        if x.0 == y.0 {
                            *same = same.min(d);
                        } else if d > *other {
                            *other = d;
                            *pair = (x.0, y.0);
                        }
                    }
                }
            };
            let mut dummy = (0u8, 0u8);
            scan(&m, &m, &mut ms, &mut mo, &mut mpair, true);
            scan(&q, &q, &mut ss, &mut so, &mut spair, true);
            scan(&m, &q, &mut cs, &mut co, &mut dummy, false);
        }
        let name = |p: (u8, u8)| {
            format!("{}~{}", breach_core::CODES[p.0 as usize], breach_core::CODES[p.1 as usize])
        };
        println!("{:<12} | {:>8.3} / {:<6.3} ({})              | {:>8.3} / {:<6.3} ({})                 | {:>8.3} / {:<6.3}", pname, ms, mo, name(mpair), ss, so, name(spair), cs, co);
    }
    Ok(())
}
